import pandas as pd
import statsmodels.api as sm

print("ВАРИАНТ #6")

gamma = 0.955 # Надежность доверительных интервалов
alpha = 0.045 # Уровень значимости
gender = 1 # Пол нового сотрудника (1-жен, 0-муж)
experience = 7 # Стаж нового сотрудника (лет)
edu_time = 10 # Время на образование нового сотрудника (лет)

data = pd.read_excel("LAB_6_DATA_2025_PART_1.xlsx", sheet_name='lab6')

print("\nПервые 10 строк таблицы:")
print(data.iloc[:10, :4])

print("\n=== Пункт 1: Регрессия Зарплата ~ ПОЛ ===")

# Пункт 1: Модель 1 - Зарплата от Пол
y = data['Зарплата (долл. в час)']

X_z = sm.add_constant(data['ПОЛ (1-жен, 0- муж)'])
model_z = sm.OLS(y, X_z).fit()
print(model_z.summary())

print("\n=== Пункт 2: Объясняющая способности модели 1 ===")

# Пункт 2: Проверка объясняющей способности модели
r2_z = model_z.rsquared
f_stat_z = model_z.fvalue
f_pvalue_z = model_z.f_pvalue

print(f"\nR^2 модели (Зарплата ~ ПОЛ): {r2_z:.4f}")
print(f"F-статистика: {f_stat_z:.3f}, p-value: {f_pvalue_z:.4e}")

if r2_z > 0.5 and f_pvalue_z < alpha:
    print("Модель обладает высокой объясняющей способностью")
else:
    print("Модель низкого качества")

print("\n=== Пункт 3: Модель 2: Регрессия Зарплата ~ Стаж + Образование + Пол ===")

# Пункт 3: Регрессия Зарплата ~ Стаж + Образование + Пол

y = data['Зарплата (долл. в час)']

X_all = data[['СТАЖ РАБОТЫ (лет)', 'ВРЕМЯ, ЗАТРАЧЕННОЕ НА ОБРАЗОВАНИЕ (лет)', 'ПОЛ (1-жен, 0- муж)']]
X_all = sm.add_constant(X_all)
model_all = sm.OLS(y, X_all).fit()
print(model_all.summary())

print("\n=== Пункт 4: Объясняющая способности модели 2===")

# Пункт 4: Проверка объясняющей способности модели
r2_all = model_all.rsquared
f_stat_all = model_all.fvalue
f_pvalue_all = model_all.f_pvalue

print(f"\nR^2 модели (Зарплата ~ Стаж + Образование + Пол): {r2_all:.4f}")
print(f"F-статистика: {f_stat_all:.3f}, p-value: {f_pvalue_all:.4e}")

if r2_all > 0.5 and f_pvalue_all < alpha:
    print("Модель обладает высокой объясняющей способностью")
else:
    print("Модель низкого качества")


# Пункты 5, 6, 7: Значимость коэффициентов

print("\n=== Пункт 5: Значимость коэффициента при ПОЛ ===")

p_value_gender = model_all.pvalues['ПОЛ (1-жен, 0- муж)']
print(f"p-value для ПОЛ: {p_value_gender:.4e}")

if p_value_gender < alpha:
    print("Различия зарплат мужчин и женщин значимы при прочих равных условиях")
else:
    print("Различия незначимы")

print("\n=== Пункт 6: Значимость коэффициента при СТАЖЕ РАБОТЫ ===")
p_value_exp = model_all.pvalues['СТАЖ РАБОТЫ (лет)']
print(f"p-value для СТАЖА РАБОТЫ: {p_value_exp:.4e}")
if p_value_exp < alpha:
    print("Коэффициент при СТАЖЕ РАБОТЫ отражает истинную зависимость")
else:
    print("Коэффициент при СТАЖЕ РАБОТЫ может быть случайным")


print("\n=== Пункт 7: Значимость коэффициента при ОБРАЗОВАНИИ ===")
p_value_edu = model_all.pvalues['ВРЕМЯ, ЗАТРАЧЕННОЕ НА ОБРАЗОВАНИЕ (лет)']
print(f"p-value для ВРЕМЯ, ЗАТРАЧЕННОЕ НА ОБРАЗОВАНИЕ: {p_value_edu:.4e}")
if p_value_edu < alpha:
    print("Коэффициент при ОБРАЗОВАНИИ отражает истинную зависимость")
else:
    print("Коэффициент при ОБРАЗОВАНИИ может быть случайным")


# Пункт 8: Доверительные интервалы для теоретических коэффициентов регрессии модели

print("\n=== Пункт 8: Доверительные интервалы ===")

conf_int = model_all.conf_int(alpha=alpha)
conf_int.columns = ['Нижняя граница', 'Верхняя граница']

print("\nДоверительные интервалы для коэффициентов модели 2:")
print(f"(Уровень доверия: {gamma*100}%, α = {alpha})")
print("-" * 70)
print(conf_int)
print("-" * 70)

print("\nИНТЕРПРЕТАЦИЯ:")
print(f"С надежностью {gamma*100}% можно сказать следующее о коэффициентах модели:")

print(f"1. Свободный член модели (константа) β₀ находится в диапазоне от {conf_int.loc['const', 'Нижняя граница']:.2f} до {conf_int.loc['const', 'Верхняя граница']:.2f}.")
print(f"   Это значение соответствует прогнозируемой зарплате, когда все факторы равны нулю (теоретическая базовая зарплата).")

print(f"2. Коэффициент при стаже β₁ лежит в пределах от {conf_int.loc['СТАЖ РАБОТЫ (лет)', 'Нижняя граница']:.2f} до {conf_int.loc['СТАЖ РАБОТЫ (лет)', 'Верхняя граница']:.2f}.")
print(f"   То есть каждый дополнительный год стажа повышает зарплату примерно на это значение долларов в час.")

print(f"3. Коэффициент при времени на образование β₂ находится между {conf_int.loc['ВРЕМЯ, ЗАТРАЧЕННОЕ НА ОБРАЗОВАНИЕ (лет)', 'Нижняя граница']:.2f} и {conf_int.loc['ВРЕМЯ, ЗАТРАЧЕННОЕ НА ОБРАЗОВАНИЕ (лет)', 'Верхняя граница']:.2f}.")
print(f"   Каждый дополнительный год обучения увеличивает зарплату примерно на эту величину.")

print(f"4. Коэффициент при поле β₃ лежит в диапазоне от {conf_int.loc['ПОЛ (1-жен, 0- муж)', 'Нижняя граница']:.2f} до {conf_int.loc['ПОЛ (1-жен, 0- муж)', 'Верхняя граница']:.2f}.")
print(f"   Отрицательное значение говорит о том, что женщины получают зарплату ниже мужчин при прочих равных условиях, положительное — выше.")


# Пункт 9: Интервальная оценка прогнозной зарплаты
print("\n=== Пункт 9: Интервальная оценка прогнозной зарплаты ===")

new_employee = pd.DataFrame({
    'const': [1],  # Константа
    'СТАЖ РАБОТЫ (лет)': [experience],
    'ВРЕМЯ, ЗАТРАЧЕННОЕ НА ОБРАЗОВАНИЕ (лет)': [edu_time],
    'ПОЛ (1-жен, 0- муж)': [gender]
})

pred = model_all.get_prediction(new_employee)
pred_summary = pred.summary_frame(alpha=alpha)  # alpha = 1 - gamma

print("\nПрогноз зарплаты с доверительным интервалом:")
print(pred_summary[['mean', 'mean_ci_lower', 'mean_ci_upper', 'obs_ci_lower', 'obs_ci_upper']])

print("\nИНТЕРПРЕТАЦИЯ:")
print(f"1. Ожидаемая средняя зарплата сотрудника с заданными характеристиками: {pred_summary['mean'][0]:.2f} долл./час")
print(f"2. Доверительный интервал для средней зарплаты сотрудников с такими же характеристиками: "
      f"[{pred_summary['mean_ci_lower'][0]:.2f}, {pred_summary['mean_ci_upper'][0]:.2f}] долл./час")
print(f"   (С надежностью {gamma*100:.1f}% средняя зарплата таких сотрудников находится в этом диапазоне.)")
print(f"3. Прогнозный интервал для зарплаты конкретного сотрудника: "
      f"[{pred_summary['obs_ci_lower'][0]:.2f}, {pred_summary['obs_ci_upper'][0]:.2f}] долл./час")
print(f"   (С надежностью {gamma*100:.1f}% зарплата этого конкретного сотрудника находится в этом диапазоне.)")

print("\n=== Пункт 10: Изменение зарплаты при увеличении стажа на 2 года ===")

# Пункт 10: Изменение зарплаты при увеличении стажа на 2 года
coef_exp = model_all.params['СТАЖ РАБОТЫ (лет)']  # Коэффициент при стаже
delta_exp = 2  # Увеличение стажа на 2 года

change_salary = coef_exp * delta_exp

print(f"Коэффициент при стаже: {coef_exp:.4f} долл./час за год")
print(f"Если стаж увеличится на {delta_exp} года,")
print(f"в среднем зарплата увеличится на {change_salary:.2f} долл./час")

print("\n=== Пункт 11: Прибавка к зарплате за дополнительный год образования ===")

# Пункт 11: Прибавка к зарплате за дополнительный год образования
coef_edu = model_all.params['ВРЕМЯ, ЗАТРАЧЕННОЕ НА ОБРАЗОВАНИЕ (лет)']  # Коэффициент при образовании

print(f"Коэффициент при образовании: {coef_edu:.4f} долл./час за год")
print(f"Это значит, что каждый дополнительный год обучения увеличивает среднюю зарплату на {coef_edu:.2f} долл./час")

print("\n=== Пункт 12: Гендерная дискриминация ===")

# Пункт 12: Гендерная дискриминация
coef_gender = model_all.params['ПОЛ (1-жен, 0- муж)']  # Коэффициент при поле
p_value_gender = model_all.pvalues['ПОЛ (1-жен, 0- муж)']  # p-value для проверки значимости

print(f"Коэффициент при поле: {coef_gender:.4f} долл./час")
print(f"p-value: {p_value_gender:.4e}")

if p_value_gender < alpha:
    if coef_gender < 0:
        print("При прочих равных условиях женщины получают меньше мужчин — есть признаки дискриминации по гендеру.")
    else:
        print("При прочих равных условиях женщины получают больше мужчин — есть отклонение в оплате по гендеру.")
else:
    print("Различия по полу статистически незначимы — дискриминации по гендеру не выявлено.")

print('='*80)
print("\nТЕОРИЯ:")
